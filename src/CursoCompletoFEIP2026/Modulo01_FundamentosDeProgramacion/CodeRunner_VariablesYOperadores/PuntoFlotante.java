package CursoCompletoFEIP2026.Modulo01_FundamentosDeProgramacion.CodeRunner_VariablesYOperadores;

public class PuntoFlotante {
    public static void main(String[] args) {
        // Ejemplo de float
        float numeroFloat = 3.14f;
        System.out.println("Valor float: " + numeroFloat);

        // Ejemplo de double
        double numeroDouble = 3.141592653589793;
        System.out.println("Valor double: " + numeroDouble);

        // Ejemplo de char
        char caracter = 'A';
        System.out.println("Valor char: " + caracter);

        char unicodico = '\u0041';
        System.out.println("Valor char unicode: " + unicodico);

        char asciChar = 65;
        System.out.println("Valor char ASCII: " + asciChar);

        // Ejemplo de boolean
        boolean esVerdadero = true;
        System.out.println("Valor boolean: " + esVerdadero);
    }
}
