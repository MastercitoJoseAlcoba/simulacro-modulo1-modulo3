package Bloque9_Ejercicios_repetidos_no_duplicados.Pregunta14_Tipo_de_retorno;

public class Main {
    public static boolean esPar(int numero) {

        // boolean es el tipo de retorno.
        //
        // Este método devuelve true o false.
        return numero % 2 == 0;
    }

/*
FIRMA:

public static boolean esPar(int numero)

public:
modificador de acceso.

static:
se puede llamar sin crear objeto.

boolean:
tipo de retorno.

esPar:
nombre del método.

int numero:
parámetro.

IDEA CLAVE:

Lo que aparece antes del nombre del método
es el tipo de retorno.

public int sumar()
public String getNombre()
public boolean esPar()
public void imprimir()
*/
}
