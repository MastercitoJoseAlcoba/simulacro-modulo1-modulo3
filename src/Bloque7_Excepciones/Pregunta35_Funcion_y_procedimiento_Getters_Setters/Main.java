package Bloque7_Excepciones.Pregunta35_Funcion_y_procedimiento_Getters_Setters;

public class Main {
    public String getNombre() {

        // ================================
        // PREGUNTA 35 — FUNCIÓN Y PROCEDIMIENTO
        // ================================
        //
        // Este método se llama getNombre().
        //
        // Tiene tipo de retorno String.
        //
        // Eso significa que devuelve un valor de tipo String.
        //
        // Como devuelve algo,
        // en teoría se considera una FUNCIÓN.
        //
        // En Java técnicamente todo esto son métodos,
        // pero para teoría se suele distinguir:
        //
        // función:
        // devuelve valor.
        //
        // procedimiento:
        // no devuelve valor.

        String nombre = "";
        return nombre;

        // return nombre;
        //
        // devuelve el contenido del atributo nombre.
        //
        // Ejemplo:
        //
        // Si nombre = "Ana"
        //
        // getNombre() devuelve:
        //
        // "Ana"
    }
}
